"""Engine B (homogenized Apery set).

Minimum factorization lengths m(n) over the positive parts by dynamic programming, the
Apery set of the homogenized semigroup generated by the points (1, a), a in A_0, with
respect to (1, 0) and (1, d), and h A_0 rebuilt from that Apery set.

Search bound: a minimum-length representation of n uses at most d - 1 parts other than d
(pigeonhole on prefix sums modulo d: d such parts contain a nonempty subset summing to t*d
with t smaller than its size, and replacing it by t copies of d shortens the
representation). Hence n >= (d-1)*a_{k-1} + d forces a part d in every minimum
representation, m(n - d) = m(n) - 1, and n is not an Apery element.
"""

INF = 1 << 60


def min_lengths(A0, N):
    gens = [a for a in A0 if a > 0]
    m = [INF] * (N + 1)
    m[0] = 0
    for n in range(1, N + 1):
        best = INF
        for a in gens:
            if a <= n:
                v = m[n - a]
                if v < best:
                    best = v
        m[n] = best + 1 if best < INF else INF
    return m


def apery_bound(A0):
    gens = sorted(a for a in A0 if a > 0)
    d = gens[-1]
    second = gens[-2] if len(gens) > 1 else 0
    return (d - 1) * second + d - 1


def apery(A0):
    """Apery set of the homogenized semigroup, as a sorted list of pairs (level, n)."""
    d = max(A0)
    N = apery_bound(A0)
    m = min_lengths(A0, N)
    ap = []
    for n in range(N + 1):
        if m[n] >= INF:
            continue
        if n < d or m[n - d] >= INF or m[n - d] >= m[n]:
            ap.append((m[n], n))
    return sorted(ap)


def is_cm(A0, ap=None):
    """Cohen-Macaulay test: the Apery set has exactly d elements."""
    ap = apery(A0) if ap is None else ap
    return len(ap) == max(A0)


def sumset_series_from_apery(A0, H, ap=None):
    """Bitsets of h A_0 for h = 0..H, from h A_0 = union over Apery (h', n') with h' <= h
    of {n' + j d : 0 <= j <= h - h'}."""
    d = max(A0)
    ap = apery(A0) if ap is None else ap
    by_level = {}
    for hh, n in ap:
        by_level.setdefault(hh, []).append(n)
    out = []
    cur = 0
    for h in range(H + 1):
        cur = cur | (cur << d)
        for n in by_level.get(h, []):
            cur |= 1 << n
        out.append(cur)
    return out


def undershoot_formula(A0, h, T, ap=None):
    """D_h(T) = T - max over Apery (h', n') with h' <= h, n' <= T of
    n' + d * min(h - h', floor((T - n') / d))."""
    d = max(A0)
    ap = apery(A0) if ap is None else ap
    best = -1
    for hh, n in ap:
        if hh <= h and n <= T:
            v = n + d * min(h - hh, (T - n) // d)
            if v > best:
                best = v
    return T - best
