#!/usr/bin/env python3
"""Optional computer-algebra check of lem:family-ci with Groebner bases (needs sympy).

For coprime 0 < a < b, the ideal of the monomial curve of A_0 = {0, a, b, 2b} is computed by
eliminating s, t from x_i - s^(a_i) t^(2b - a_i) (lex order s > t > x0 > x1 > x2 > x3), and its
reduced Groebner basis is compared with that of the ideal generated by
    x2^2 - x0 x3   and   x1^b - x2^j x0^z x3^w,   j = a mod 2, w = (a - j)/2, z = (2b - a - j)/2,
over the rationals and over the fields with 2 and 3 elements. Two negative controls must fail:
the set {0, 1, 3, 4}, whose ideal needs four generators, against two of its binomials, and the
family binomials with a wrong exponent. This check shares no code with src/.

Usage: python3 cas/check_ideal_sympy.py [--quick]
Writes cas/output/ideal.json and compares it with cas/expected-ideal.json; exits nonzero on any
mismatch. The output holds counts and booleans only, so it does not depend on the sympy version.
"""
import json
import os
import sys
from math import gcd

from sympy import groebner, symbols

HERE = os.path.dirname(os.path.abspath(__file__))
s, t, x0, x1, x2, x3 = symbols("s t x0 x1 x2 x3")
X = (x0, x1, x2, x3)


def curve_ideal(A0, modulus):
    d = A0[-1]
    opts = {} if modulus is None else {"modulus": modulus}
    gens = [x - s ** a * t ** (d - a) for x, a in zip(X, A0)]
    G = groebner(gens, s, t, *X, order="lex", **opts)
    return sorted((g for g in G.exprs if not (g.has(s) or g.has(t))), key=str)


def generated(polys, modulus):
    opts = {} if modulus is None else {"modulus": modulus}
    return sorted(groebner(polys, *X, order="lex", **opts).exprs, key=str)


def family_binomials(a, b, wrong=False):
    j = a % 2
    w = (a - j) // 2
    z = (2 * b - a - j) // 2
    return [x2 ** 2 - x0 * x3, x1 ** b - x2 ** j * x0 ** (z + (1 if wrong else 0)) * x3 ** w]


def main():
    quick = "--quick" in sys.argv[1:]
    bmax = 6 if quick else 12
    fields = [None, 2, 3]
    names = {None: "rationals", 2: "GF(2)", 3: "GF(3)"}
    checked = {names[p]: 0 for p in fields}
    failures = []
    for b in range(2, bmax + 1):
        for a in range(1, b):
            if gcd(a, b) != 1:
                continue
            for p in fields:
                checked[names[p]] += 1
                if curve_ideal([0, a, b, 2 * b], p) != generated(family_binomials(a, b), p):
                    failures.append([a, b, names[p]])
    controls = {
        "{0,1,3,4} against two of its binomials (must differ)":
            curve_ideal([0, 1, 3, 4], None) != generated([x1 * x2 - x0 * x3, x2 ** 3 - x1 * x3 ** 2], None),
        "a = 3, b = 5 with a wrong exponent (must differ)":
            curve_ideal([0, 3, 5, 10], None) != generated(family_binomials(3, 5, wrong=True), None),
    }
    report = {
        "check": "lem:family-ci: the ideal of {0,a,b,2b} is generated by the two binomials (Groebner bases)",
        "bounds": {"b_max": bmax, "fields": [names[p] for p in fields]},
        "pairs_checked_per_field": checked,
        "failures": failures,
        "negative_controls_detected": controls,
        "status": "pass" if not failures and all(controls.values()) else "FAIL",
    }
    os.makedirs(os.path.join(HERE, "output"), exist_ok=True)
    out = os.path.join(HERE, "output", "ideal-quick.json" if quick else "ideal.json")
    with open(out, "w", encoding="ascii", newline="\n") as fh:
        fh.write(json.dumps(report, sort_keys=True, indent=1, separators=(",", ": ")) + "\n")
    expected = os.path.join(HERE, "expected-ideal-quick.json" if quick else "expected-ideal.json")
    same = os.path.exists(expected) and open(expected, "rb").read() == open(out, "rb").read()
    total = sum(checked.values())
    print("lem:family-ci (sympy)              %s  (%d pairs x fields, %d failures, controls %s)"
          % (report["status"], total, len(failures), "ok" if all(controls.values()) else "FAILED"))
    print("output: %s" % ("identical to " + os.path.basename(expected) if same else "DIFFERS from " + os.path.basename(expected)))
    sys.exit(0 if report["status"] == "pass" and same else 1)


if __name__ == "__main__":
    main()
